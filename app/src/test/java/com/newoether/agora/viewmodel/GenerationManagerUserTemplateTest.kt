package com.newoether.agora.viewmodel

import com.newoether.agora.data.SYSTEM_NOTICE_MARK
import com.newoether.agora.data.wireSystemNotice
import com.newoether.agora.data.wireTimeLine
import com.newoether.agora.data.wireWorkModeLine
import com.newoether.agora.model.ChatMessage
import com.newoether.agora.model.MessageSegment
import com.newoether.agora.model.Participant
import com.newoether.agora.model.ToolCallData
import com.newoether.agora.util.Constants
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Test
import java.time.ZoneId
import java.time.ZonedDateTime

class GenerationManagerUserTemplateTest {
    @Test
    fun applyUserTemplateToMessages_wrapsOnlyNormalUserMessages() {
        val messages = listOf(
            ChatMessage(id = "u1", text = "hello", participant = Participant.USER),
            ChatMessage(id = Constants.RESULT_MSG_PREFIX + "r1", text = "tool output", participant = Participant.USER),
            ChatMessage(
                id = Constants.PROCESS_NOTICE_MSG_PREFIX + "p1",
                text = "【系统提示】\nprocess: 后台进程已结束\n\noutput:\ndump",
                participant = Participant.USER,
            ),
            ChatMessage(id = Constants.TOOL_MSG_PREFIX + "t1", text = "", participant = Participant.MODEL),
            ChatMessage(id = "m1", text = "assistant", participant = Participant.MODEL)
        )

        val result = applyUserTemplateToMessages(messages, "<wrap>", "</wrap>")

        assertEquals("<wrap>hello</wrap>", result[0].text)
        assertEquals("tool output", result[1].text)
        assertEquals("【系统提示】\nprocess: 后台进程已结束\n\noutput:\ndump", result[2].text)
        assertEquals("", result[3].text)
        assertEquals("assistant", result[4].text)
    }

    @Test
    fun exactInputProjectionAppliesTemplatesAndRelocatesAssistantImagesOnce() {
        val zone = ZoneId.of("UTC")
        val messages = listOf(
            ChatMessage(
                id = "assistant-image",
                text = "generated",
                images = listOf("generated.png"),
                participant = Participant.MODEL,
                timestamp = 0L,
            ),
            ChatMessage(id = "latest-user", text = "inspect", participant = Participant.USER, timestamp = 0L),
        )

        val projected = projectGenerationInputMessages(
            messages = messages,
            includeImages = true,
            userPrepend = "<",
            userPostpend = ">",
            zone = zone,
        )

        assertEquals(emptyList<String>(), projected[0].images)
        assertEquals(listOf("generated.png"), projected[1].images)
        val body = "<[Visual context: the first attached image was generated by the assistant earlier in this conversation.]\n\ninspect>"
        val notice = wireSystemNotice(listOf(wireTimeLine(0L, zone), wireWorkModeLine(false)))
        assertEquals("$body\n\n$notice", projected[1].text)
    }

    @Test
    fun compactInvocationIsAnApiOnlyFinalUserMessage() {
        val durableMessages = listOf(
            ChatMessage(id = "user", text = "question", participant = Participant.USER),
            ChatMessage(id = "assistant", text = "answer", participant = Participant.MODEL),
        )

        val projected = projectGenerationInputMessages(
            messages = durableMessages,
            includeImages = true,
            userPrepend = null,
            userPostpend = null,
            initialUserPrompt = "Create the compact context summary now.",
        )

        assertEquals(durableMessages.size + 1, projected.size)
        assertEquals("answer", projected[1].text)
        assertEquals(Participant.USER, projected.last().participant)
        assertEquals("Create the compact context summary now.", projected.last().text)
        assertEquals("assistant", projected.last().parentId)
    }

    @Test
    fun projectGenerationInputMessages_appendsSystemNoticeByRole() {
        val zone = ZoneId.of("Asia/Shanghai")
        val epoch = ZonedDateTime.of(2026, 10, 3, 3, 21, 0, 0, zone).toInstant().toEpochMilli()
        val timeLine = wireTimeLine(epoch, zone)
        val processText = wireSystemNotice(listOf(timeLine, "process: 后台进程已结束"))
        val messages = listOf(
            ChatMessage(id = "u1", text = "hello", participant = Participant.USER, timestamp = epoch),
            ChatMessage(id = "u-empty", text = "", participant = Participant.USER, timestamp = epoch),
            ChatMessage(
                id = Constants.RESULT_MSG_PREFIX + "r1",
                text = "tool output",
                participant = Participant.USER,
                timestamp = epoch,
                toolCall = ToolCallData("echo", "{}", "tool output"),
            ),
            ChatMessage(
                id = Constants.RESULT_MSG_PREFIX + "r2",
                text = "segment output",
                participant = Participant.USER,
                timestamp = epoch,
                segments = listOf(MessageSegment(type = "tool", toolResult = "segment output")),
            ),
            ChatMessage(id = "context_summary_compact_1", text = "old summary", participant = Participant.USER, timestamp = epoch),
            ChatMessage(id = "m1", text = "assistant", participant = Participant.MODEL, timestamp = epoch),
            ChatMessage(
                id = Constants.PROCESS_NOTICE_MSG_PREFIX + "process",
                text = processText,
                participant = Participant.USER,
                timestamp = epoch,
            ),
        )
        listOf(false, true).forEach { askMode ->
            val projected = projectGenerationInputMessages(
                messages = messages,
                includeImages = true,
                userPrepend = null,
                userPostpend = null,
                initialUserPrompt = "Create the compact context summary now.",
                askMode = askMode,
                zone = zone,
            )
            val timeOnly = wireSystemNotice(listOf(timeLine))
            val userNotice = wireSystemNotice(listOf(timeLine, wireWorkModeLine(askMode)))
            val toolNotice = wireSystemNotice(listOf(timeLine))
            assertEquals("ask=$askMode older user", "hello\n\n$timeOnly", projected[0].text)
            assertFalse("ask=$askMode older mode", "工作模式：" in projected[0].text)
            assertEquals("ask=$askMode latest user", userNotice, projected[1].text)
            assertEquals("ask=$askMode tool text", "tool output", projected[2].text)
            assertEquals("ask=$askMode tool result", "tool output\n\n$toolNotice", projected[2].toolCall?.result)
            assertEquals("ask=$askMode segment text", "segment output", projected[3].text)
            assertEquals(
                "ask=$askMode segment result",
                "segment output\n\n$toolNotice",
                projected[3].segments?.single()?.toolResult,
            )
            assertFalse("ask=$askMode tool mode", "工作模式：" in projected[2].toolCall?.result.orEmpty())
            assertEquals("ask=$askMode summary", "old summary", projected[4].text)
            assertEquals("ask=$askMode assistant", "assistant", projected[5].text)
            assertEquals("ask=$askMode process", processText, projected[6].text)
            assertEquals("ask=$askMode compact", "Create the compact context summary now.", projected.last().text)
            assertFalse(SYSTEM_NOTICE_MARK in projected.last().text)
        }
    }
}
